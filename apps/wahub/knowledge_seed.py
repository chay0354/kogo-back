def _note(kind: str, source: str, title: str, decision: str = '') -> str:
    """Unique per record (kind, source row, title): the import keys on it."""
    note = f'{IMPORT_TAG} · {kind} · {source} · {title}'
    return f'{note} · {decision}' if decision else note


def R(kind, source, title, body='', *, key='', decision='', active=True, when=WHEN_PROACTIVE, scope=None,
      good='', bad='', valid_from=None, valid_until=None, **data):
    """One record. `scope` = (level, label) when not the whole business."""
    # `when` is the when_to_say switch when it is one of its values; for a
    # phrasing, a contact or a link it is the free text "מתי" and goes into data.
    if when not in (WHEN_PROACTIVE, WHEN_IF_ASKED, WHEN_INTERNAL):
        data = {**data, 'when': when}
        when = WHEN_PROACTIVE
    record = {
        'kind': kind, 'key': key, 'title': title, 'body': body, 'when_to_say': when,
        'is_active': active, 'example_good': good, 'example_bad': bad,
        'valid_from': valid_from.isoformat() if valid_from else None,
        'valid_until': valid_until.isoformat() if valid_until else None,
        'source_note': _note(kind, source, title, decision),
        'scope_level': SCOPE_BUSINESS, 'scope_label': '',
        'data': data,
    }
    if scope:
        record['scope_level'], record['scope_label'] = scope
    return record


