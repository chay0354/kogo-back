def _season_date(day_month: str) -> date:
    day, month = (int(part) for part in day_month.split('.'))
    year = SEASON_START.year if month >= 9 else SEASON_END.year
    return date(year, month, day)


def _special(source, line, scope=None):
    """One line of the holiday list, as it was written, turned into a special day."""
    dates, _, rest = line.partition(' ')
    name, _, status = rest.rpartition(' - ')
    start_text, _, end_text = dates.partition('-')
    start = _season_date(start_text)
    end = _season_date(end_text) if end_text else start
    status_text = status.strip()
    state, hours_to = SPECIAL_OPEN, None
    if 'סגור' in status_text:
        state = SPECIAL_CLOSED
    elif 'שקטה' in status_text:
        state = SPECIAL_QUIET
        if 'עד' in status_text:
            hours_to = status_text.rsplit('עד', 1)[1].strip()
    elif 'ייסגר בשעה' in status_text or 'עד' in status_text:
        state = SPECIAL_HOURS
        hours_to = status_text.replace('הסטודיו ייסגר בשעה', '').replace('פעילות כרגיל עד', '').strip()
    record = R(KIND_SPECIAL_DAY, source, name.strip(), f'🔹 {line}', scope=scope, active=True,
               date_from=start.isoformat(), date_to=end.isoformat(), state=state, hours_from=None, hours_to=hours_to,
               message=f'🔹 *{start_text}* {name.strip()} - {status_text}')
    record['_dates'] = (start, end)
    return record


